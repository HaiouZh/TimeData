const cache = new Map<string, string>();

/**
 * 按当前路径返回对应模块图标的 svg data-URI，作为 <link rel="icon"> 的 href。
 * 命中不到模块图标（理论上不会发生，主路由都有 icon）时返回 null，让调用方保持现状。
 */
export function faviconDataUriForPath(pathname: string): string | null {
  const route = primaryRouteForPath(pathname);
  const cached = cache.get(route);
  if (cached) return cached;

  const item = findMainNavItem(route);
  const d = item ? ICON_PATHS[item.iconName] : undefined;
  if (!d) return null;

  // 深色圆角底 + 浅色字形，保证在浅色/深色标签栏下都清晰可辨。
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="64" height="64">` +
    `<rect width="256" height="256" rx="56" fill="${TILE_COLOR}"/>` +
    `<g transform="translate(40 40) scale(0.6875)" fill="${GLYPH_COLOR}"><path d="${d}"/></g>` +
    `</svg>`;
  const uri = `data:image/svg+xml,${encodeURIComponent(svg)}`;
  cache.set(route, uri);
  return uri;
}
